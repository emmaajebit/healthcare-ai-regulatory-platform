#!/usr/bin/env bash
# terraform-to-ansible.sh — Reads `terraform output -json` and writes:
#   • ansible/inventory/hosts.yml   — dynamic inventory populated from TF state
#   • ansible/playbooks/group_vars/all.yml — non-sensitive vars for playbooks
#
# Run from the repo root after `terraform apply`:
#   bash scripts/terraform-to-ansible.sh
#
# Or as part of a CI pipeline step after the Terraform apply job.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TF_DIR="${REPO_ROOT}/infrastructure/terraform"
INVENTORY_FILE="${REPO_ROOT}/ansible/inventory/hosts.yml"
GROUP_VARS_FILE="${REPO_ROOT}/ansible/playbooks/group_vars/all.yml"
TOOL_VERSIONS_FILE="/tmp/tool-versions.json"

log()  { echo "[$(date '+%H:%M:%S')] $*"; }
die()  { echo "ERROR: $*" >&2; exit 1; }

# ─── Pre-flight checks ────────────────────────────────────────────────────────

command -v terraform &>/dev/null || die "terraform not found — run install-devops-tools.sh first"
command -v jq        &>/dev/null || die "jq not found — run install-devops-tools.sh first"

[[ -d "$TF_DIR" ]] || die "Terraform directory not found: $TF_DIR"

# ─── Fetch Terraform outputs ──────────────────────────────────────────────────

log "Fetching terraform outputs from ${TF_DIR} ..."
cd "$TF_DIR"

# -json includes sensitive values — keep the output in memory only
TF_JSON="$(terraform output -json 2>/dev/null)" \
  || die "terraform output failed. Is the workspace initialised and applied?"

extract() {
  # extract(key) → raw string value, empty string if missing or null
  echo "$TF_JSON" | jq -r --arg k "$1" '.[$k].value // ""'
}

EKS_CLUSTER_NAME="$(extract eks_cluster_name)"
EKS_ENDPOINT="$(extract eks_cluster_endpoint)"
ECR_URL="$(extract ecr_repository_url)"
OPENSEARCH_ENDPOINT="$(extract opensearch_endpoint)"
WORM_BUCKET="$(extract worm_bucket_name)"
AUDIT_TABLE="$(extract audit_dynamodb_table)"
AWS_REGION="$(extract aws_region)"
DEPLOYER_ROLE="$(extract terraform_deployer_role_arn)"
PLANNER_ROLE="$(extract terraform_planner_role_arn)"
ARGOCD_SECRET_ARN="$(extract argocd_secret_arn)"
APP_SECRET_ARN="$(extract app_secret_arn)"
HELM_SECRET_ARN="$(extract helm_repo_secret_arn)"
GRAFANA_SECRET_ARN="$(extract grafana_secret_arn)"
SECRETS_READER_POLICY="$(extract secrets_reader_policy_arn)"

log "EKS cluster : ${EKS_CLUSTER_NAME}"
log "ECR repo    : ${ECR_URL}"
log "Region      : ${AWS_REGION}"

# ─── Write ansible/inventory/hosts.yml ───────────────────────────────────────

log "Writing ${INVENTORY_FILE} ..."
mkdir -p "$(dirname "$INVENTORY_FILE")"

cat > "$INVENTORY_FILE" <<YAML
# AUTO-GENERATED by scripts/terraform-to-ansible.sh — do not edit by hand.
# Regenerate with: bash scripts/terraform-to-ansible.sh
# Generated: $(date -u +%Y-%m-%dT%H:%M:%SZ)

all:
  vars:
    aws_region: "${AWS_REGION}"

  children:
    eks:
      hosts:
        eks_cluster:
          ansible_connection: local
          eks_cluster_name: "${EKS_CLUSTER_NAME}"
          eks_cluster_endpoint: "${EKS_ENDPOINT}"

    ecr:
      hosts:
        ecr_registry:
          ansible_connection: local
          ecr_repository_url: "${ECR_URL}"

    storage:
      hosts:
        worm_bucket:
          ansible_connection: local
          s3_worm_bucket: "${WORM_BUCKET}"
          dynamodb_audit_table: "${AUDIT_TABLE}"

    search:
      hosts:
        opensearch:
          ansible_connection: local
          opensearch_endpoint: "${OPENSEARCH_ENDPOINT}"
YAML

log "Inventory written."

# ─── Write ansible/playbooks/group_vars/all.yml ───────────────────────────────
# Secrets are referenced by ARN only — actual values fetched at runtime
# from AWS Secrets Manager by the playbook (amazon.aws.secretsmanager_secret lookup).

log "Writing ${GROUP_VARS_FILE} ..."
mkdir -p "$(dirname "$GROUP_VARS_FILE")"

# Load tool versions if available
TOOL_VERSIONS_BLOCK=""
if [[ -f "$TOOL_VERSIONS_FILE" ]]; then
  TOOL_VERSIONS_BLOCK="$(jq -r '
    "tool_versions:\n" +
    (.tool_versions | to_entries | map("  \(.key): \"\(.value)\"") | join("\n"))
  ' "$TOOL_VERSIONS_FILE")"
fi

cat > "$GROUP_VARS_FILE" <<YAML
# AUTO-GENERATED by scripts/terraform-to-ansible.sh — do not edit by hand.
# Secrets are stored in AWS Secrets Manager; fetched with the amazon.aws.secretsmanager_secret lookup.
# Generated: $(date -u +%Y-%m-%dT%H:%M:%SZ)

# ── Infrastructure ────────────────────────────────────────────────────────────
aws_region: "${AWS_REGION}"
eks_cluster_name: "${EKS_CLUSTER_NAME}"
ecr_repository_url: "${ECR_URL}"
opensearch_endpoint: "${OPENSEARCH_ENDPOINT}"
s3_worm_bucket: "${WORM_BUCKET}"
dynamodb_audit_table: "${AUDIT_TABLE}"

# ── IAM / OIDC ────────────────────────────────────────────────────────────────
terraform_deployer_role_arn: "${DEPLOYER_ROLE}"
terraform_planner_role_arn: "${PLANNER_ROLE}"
secrets_reader_policy_arn: "${SECRETS_READER_POLICY}"

# ── Secrets Manager ARNs (values fetched at runtime, never stored here) ───────
argocd_secret_arn: "${ARGOCD_SECRET_ARN}"
app_secret_arn: "${APP_SECRET_ARN}"
helm_repo_secret_arn: "${HELM_SECRET_ARN}"
grafana_secret_arn: "${GRAFANA_SECRET_ARN}"

# ── Fetch secret values in a playbook task like this: ─────────────────────────
# - name: Fetch ArgoCD secret from Secrets Manager
#   ansible.builtin.set_fact:
#     argocd_secret: "{{ lookup('amazon.aws.secretsmanager_secret', argocd_secret_arn, region=aws_region) | from_json }}"
#   no_log: true

${TOOL_VERSIONS_BLOCK}
YAML

log "group_vars written."

# ─── Summary ──────────────────────────────────────────────────────────────────

log "═══════════════════════════════════════════════════"
log " Ansible files updated:"
log "   ${INVENTORY_FILE}"
log "   ${GROUP_VARS_FILE}"
log ""
log " Run a playbook with:"
log "   ansible-playbook -i ansible/inventory/hosts.yml \\"
log "     ansible/playbooks/deploy-eks-addons.yml"
log "═══════════════════════════════════════════════════"
